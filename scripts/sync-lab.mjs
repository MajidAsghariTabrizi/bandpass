#!/usr/bin/env node
/**
 * sync-lab — generate lab/corpus.js from the REAL compiler.
 *
 * The Lab is a visualization, never a reimplementation: every number it
 * animates is produced here by dist/ compile/explain/diff over the bundled
 * demo fixture. If the compiler changes, the Lab changes with it.
 *
 *   node scripts/sync-lab.mjs          write lab/corpus.js
 *   node scripts/sync-lab.mjs --check  fail if lab/corpus.js is stale (CI)
 */

import { writeFileSync, readFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import { loadDemoFixture } from '../dist/demo.js';
import { compileDetailed } from '../dist/compile.js';
import { explain } from '../dist/explain.js';
import { diff } from '../dist/diff.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'lab', 'corpus.js');
const PRESETS = [
  { id: 'deploy', label: 'deploy billing service to production', task: null },
  { id: 'db', label: 'investigate billing database latency', task: 'investigate billing database latency' },
];

function buildPreset(preset, fixture) {
  const task = preset.task ?? fixture.task;
  const options = { task, budget: fixture.budget, now: fixture.now, agent: 'lab' };
  const detail = compileDetailed(fixture.items, options);
  const { capsule } = detail;
  const excludedById = new Map(capsule.excluded.map((e) => [e.id, e]));
  const admitted = [...capsule.known, ...capsule.uncertain, ...capsule.unknown];
  const admittedById = new Map(admitted.map((s) => [s.id, s]));

  const items = detail.ranked
    .map((r) => {
      const sel = admittedById.get(r.item.id);
      const sup = capsule.superseded.find((s) => s.id === r.item.id);
      const ex = excludedById.get(r.item.id);
      let final = 'rejected';
      let section = null;
      let reason = null;
      let stage = null;
      let note = null;
      if (sel) {
        final = sel.kind === 'unknown' ? 'unknown' : sel.note ? 'uncertain' : 'selected';
        section = sel.kind === 'unknown' ? 'UNKNOWN' : sel.note ? 'UNCERTAIN' : 'KNOWN';
        if (sel.note) note = sel.note;
        if (sel.supersedes_summary) note = sel.supersedes_summary;
      } else if (sup) {
        final = 'superseded';
        stage = 'RESOLVE';
        reason = `superseded (${sup.reason}) by ${sup.winner_id}`;
      } else if (ex) {
        stage = ex.stage;
        reason = `${ex.reason} — ${ex.detail}`;
      }
      return {
        id: r.item.id,
        subject: r.item.subject,
        content: r.item.content,
        kind: r.item.kind,
        source: r.item.source,
        score: Number(r.score.toFixed(2)),
        lexical: Number(r.lexical_score.toFixed(2)),
        stale_days: r.stale_days ?? null,
        support: sel?.support ?? null,
        evidence: sel?.evidence ?? r.item.evidence,
        final,
        section,
        stage,
        reason,
        note,
      };
    })
    // Present items in a stable, tellable order: by descending relevance, then id.
    .sort((a, b) => b.lexical - a.lexical || (a.id < b.id ? -1 : a.id > b.id ? 1 : 0));

  const traces = {};
  for (const item of fixture.items) {
    const { trace } = explain(fixture.items, options, item.id);
    if (trace) traces[item.id] = trace;
  }

  return {
    id: preset.id,
    label: preset.label,
    task,
    budget: fixture.budget,
    stats: capsule.stats,
    used_tokens: capsule.used_tokens,
    items,
    capsule: {
      known: capsule.known,
      uncertain: capsule.uncertain,
      unknown: capsule.unknown,
      superseded: capsule.superseded,
    },
    traces,
  };
}

function build() {
  const fixture = loadDemoFixture();
  const presets = PRESETS.map((p) => buildPreset(p, fixture));
  const diffResult = diff(
    fixture.items,
    { task: presets[0].task, budget: fixture.budget, now: fixture.now },
    { task: presets[1].task, budget: fixture.budget, now: fixture.now },
  );
  const data = {
    schema: 'bandpass.lab/v1',
    presets,
    diff: { a: presets[0].task, b: presets[1].task, lines: diffResult.lines, summary: diffResult.summary },
  };
  return `// generated by scripts/sync-lab.mjs — do not edit; run: npm run lab:sync\n// deterministic output of the real compiler (dist/) over fixtures/deploy-billing.json\nwindow.BANDPASS_LAB = ${JSON.stringify(data)};\n`;
}

const generated = build();

if (process.argv.includes('--check')) {
  mkdirSync(path.dirname(OUT), { recursive: true });
  const existing = readFileSync(OUT, 'utf8');
  if (existing !== generated) {
    console.error('lab/corpus.js is out of sync with the compiler — run: npm run lab:sync');
    process.exit(1);
  }
  console.log('lab sync check OK');
} else {
  mkdirSync(path.dirname(OUT), { recursive: true });
  writeFileSync(OUT, generated);
  console.log(`wrote ${path.relative(ROOT, OUT)} (${generated.length} bytes)`);
}
