/* bandpass lab — animation engine.
   All data comes from window.BANDPASS_LAB, generated by the real compiler
   (scripts/sync-lab.mjs → dist/). This file only visualizes decisions the
   compiler already made. */

(() => {
  const LAB = window.BANDPASS_LAB;
  if (!LAB) throw new Error('lab corpus missing — run: npm run lab:sync');

  const $ = (id) => document.getElementById(id);
  const reduced = window.matchMedia('(prefers-reduced-motion: reduce)').matches;

  let preset = LAB.presets[0];
  let running = false;

  // ---------- task select ----------
  const select = $('task-select');
  for (const p of LAB.presets) {
    const opt = document.createElement('option');
    opt.value = p.id;
    opt.textContent = p.task;
    select.appendChild(opt);
  }
  select.addEventListener('change', () => {
    preset = LAB.presets.find((p) => p.id === select.value) ?? LAB.presets[0];
    reset();
  });

  // ---------- counters ----------
  const counters = {
    sources: $('c-sources'), band: $('c-band'), selected: $('c-selected'),
    conflicts: $('c-conflicts'), unknown: $('c-unknown'), tokens: $('c-tokens'),
  };
  const stageCounts = { RANK: $('s-rank'), VERIFY: $('s-verify'), RESOLVE: $('s-resolve'), COMPRESS: $('s-compress') };
  const stageEls = { RANK: $('[data-stage="RANK"]'), VERIFY: $('[data-stage="VERIFY"]'), RESOLVE: $('[data-stage="RESOLVE"]'), COMPRESS: $('[data-stage="COMPRESS"]') };

  function animateNumber(el, to, suffix = '') {
    const from = Number(String(el.textContent).replace(/[^0-9.-]/g, '')) || 0;
    if (reduced || from === to) { el.textContent = `${to}${suffix}`; return; }
    const start = performance.now();
    const dur = 500;
    const tick = (t) => {
      const k = Math.min(1, (t - start) / dur);
      el.textContent = `${Math.round(from + (to - from) * k)}${suffix}`;
      if (k < 1) requestAnimationFrame(tick);
    };
    requestAnimationFrame(tick);
  }

  // ---------- raw feed ----------
  const feedList = $('feed-list');
  const spectrumTicks = $('spectrum-ticks');

  function classify(item) {
    if (item.final === 'selected') return { cls: 'sel', label: 'PASS' };
    if (item.final === 'uncertain') return { cls: 'unc', label: 'UNCERTAIN' };
    if (item.final === 'unknown') return { cls: 'unk', label: 'UNKNOWN' };
    if (item.final === 'superseded') return { cls: 'out', label: 'SUPERSEDED' };
    return { cls: 'out', label: `× ${item.stage || 'RANK'}` };
  }

  function buildFeed() {
    feedList.innerHTML = '';
    spectrumTicks.innerHTML = '';
    const byId = new Map();
    for (const item of preset.items) {
      const row = document.createElement('div');
      const cls = classify(item);
      row.className = `feed-row ${cls.cls}`;
      row.innerHTML = `
        <span class="feed-id" title="${item.id}">${item.id}</span>
        <span class="feed-content" title="${item.content}">${item.content}</span>
        <span class="feed-rel" title="relevance (lexical ${item.lexical}${item.stale_days ? `, decayed from ${item.lexical} — ${item.stale_days}d old` : ''})">${item.score.toFixed(2)}</span>
        <span class="feed-state">${cls.label}</span>`;
      if (item.reason) row.title = item.reason;
      feedList.appendChild(row);
      byId.set(item.id, row);

      const tick = document.createElement('div');
      tick.className = 'tick';
      tick.style.left = `${Math.min(99.2, item.lexical * 100)}%`;
      tick.dataset.id = item.id;
      spectrumTicks.appendChild(tick);
    }
    return byId;
  }

  function setStage(stage, state) {
    for (const [name, el] of Object.entries(stageEls)) {
      el.classList.toggle('active', state === 'active' && name === stage);
      el.classList.toggle('done', state === 'done' && (name === stage || stageDone[name]));
    }
  }
  const stageDone = {};

  // ---------- capsule ----------
  const MARKERS = { KNOWN: '✓', UNCERTAIN: '~', UNKNOWN: '?' };
  const SECTION_ORDER = [
    { key: 'known', cls: 'known', title: 'KNOWN', items: (c) => c.known.filter((i) => i.kind !== 'mission') },
    { key: 'uncertain', cls: 'uncertain', title: 'UNCERTAIN', items: (c) => c.uncertain },
    { key: 'unknown', cls: 'unknown', title: 'UNKNOWN', items: (c) => c.unknown },
  ];

  function renderCapsule() {
    $('capsule-empty').hidden = true;
    $('capsule-body').hidden = false;
    const c = preset.capsule;
    const mission = c.known.find((i) => i.kind === 'mission');
    $('capsule-header').innerHTML = `
      <div class="ch-line"><span class="ch-k">CAPSULE</span><span>bandpass.capsule/v1 — deterministic</span></div>
      <div class="ch-line"><span class="ch-k">TASK</span><span>${escapeHtml(preset.task)}</span></div>
      <div class="ch-line"><span class="ch-k">BUDGET</span><span>${preset.budget} tokens (estimated) · USED ${preset.used_tokens}</span></div>
      ${mission ? `<div class="ch-line"><span class="ch-k">MISSION</span><span>▸ ${escapeHtml(mission.content)}</span></div>` : ''}`;

    const wrap = $('capsule-sections');
    wrap.innerHTML = '';
    for (const section of SECTION_ORDER) {
      const items = section.items(c);
      if (items.length === 0) continue;
      const div = document.createElement('div');
      div.className = `capsule-section ${section.cls}`;
      div.innerHTML = `<div class="capsule-section-title"><span class="mark">${MARKERS[section.title]}</span>${section.title} (${items.length})</div>`;
      for (const item of items) {
        const row = document.createElement('div');
        row.className = 'cap-item';
        const meta = item.kind === 'unknown'
          ? `relevance ${item.relevance.toFixed(2)}`
          : `${item.source} · support ${item.support} · relevance ${item.relevance.toFixed(2)}${item.evidence ? ` · evidence ${item.evidence}` : ''}`;
        row.innerHTML = `
          <span class="marker">${MARKERS[section.title]}</span>
          <div class="cap-content">${escapeHtml(item.content)}</div>
          <div class="cap-meta">${escapeHtml(meta)}</div>
          ${item.supersedes_summary ? `<div class="cap-note">supersedes: ${escapeHtml(item.supersedes_summary)}</div>` : ''}
          ${item.note ? `<div class="cap-note">${escapeHtml(item.note)}</div>` : ''}
          <span class="why-hint">why?</span>`;
        row.addEventListener('click', () => showWhy(item.id));
        div.appendChild(row);
      }
      wrap.appendChild(div);
    }

    if (c.superseded.length > 0) {
      const div = document.createElement('div');
      div.className = 'capsule-section';
      div.innerHTML = `<div class="capsule-section-title"><span class="mark">×</span>SUPERSEDED (${c.superseded.length}) — out of context, on the record</div>` +
        c.superseded.map((s) => `
          <div class="cap-item" style="cursor:default">
            <span class="marker" style="color:var(--red)">×</span>
            <div class="cap-content" style="text-decoration:line-through;text-decoration-color:var(--red)">${escapeHtml(s.content)}</div>
            <div class="cap-meta">${escapeHtml(s.reason)} → ${escapeHtml(s.winner_content)} (${s.winner_id})</div>
          </div>`).join('');
      wrap.appendChild(div);
    }
  }

  function showWhy(id) {
    const trace = preset.traces[id];
    if (!trace) return;
    $('why-id').textContent = id;
    $('why-body').textContent = renderTraceText(trace);
    $('why').hidden = false;
    $('why').scrollIntoView({ behavior: reduced ? 'auto' : 'smooth', block: 'nearest' });
  }
  $('why-close').addEventListener('click', () => { $('why').hidden = true; });

  function renderTraceText(trace) {
    const lines = [];
    lines.push(`subject:   ${trace.item.subject}`);
    lines.push(`content:   ${trace.item.content}`);
    lines.push(`decision:  ${trace.decision.toUpperCase()}${trace.section ? ` → ${trace.section}` : ''}`);
    lines.push(`relevance: ${trace.relevance.score.toFixed(2)} (lexical ${trace.relevance.lexical_score ?? trace.relevance.score}${trace.relevance.stale_days ? ` · ${trace.relevance.stale_days}d old, decayed` : ''}, threshold ${trace.relevance.threshold})`);
    lines.push(`matched:   subject [${trace.relevance.matched_subject_tokens}] content [${trace.relevance.matched_content_tokens}]`);
    if (trace.support) lines.push(`evidence:  authority ${trace.support.authority} · ${trace.support.evidence} source(s) → ${trace.support.grade}`);
    if (trace.resolution) lines.push(`resolve:   ${trace.resolution.outcome}${trace.resolution.winner_id ? ` → ${trace.resolution.winner_id}` : ''}${trace.resolution.reason ? ` (${trace.resolution.reason})` : ''}`);
    if (trace.budget) lines.push(`budget:    rank ${trace.budget.rank} · fit=${trace.budget.fit}`);
    lines.push(`→ ${trace.reason}`);
    return lines.join('\n');
  }

  // ---------- rejected ----------
  function renderRejected() {
    const list = $('rejected-list');
    const rejected = preset.items.filter((i) => i.final === 'rejected' || i.final === 'superseded');
    if (rejected.length === 0) {
      list.innerHTML = '<div class="capsule-empty">— nothing rejected —</div>';
      return;
    }
    list.innerHTML = rejected
      .map((i) => {
        const stage = i.stage ?? 'RESOLVE';
        const reason = i.reason ?? '';
        return `<div class="rej-row">
          <div class="rej-head">
            <span class="rej-mark">×</span><span class="rej-stage">${stage}</span>
            <span class="rej-id">${i.id}</span>
            <span class="rej-content" title="${escapeHtml(i.content)}">${escapeHtml(i.content)}</span>
          </div>
          <div class="rej-reason">${escapeHtml(reason)}</div>
        </div>`;
      })
      .join('');
  }

  // ---------- diff ----------
  function renderDiff() {
    const list = $('diff-list');
    const classByMarker = { '+': 'add', '-': 'rem', '→': 'chg', '?': 'unk', '!': 'res' };
    list.innerHTML = LAB.diff.lines
      .map((l) => `<div class="diff-row ${classByMarker[l.marker] ?? 'chg'}">
          <span class="diff-mark">${l.marker}</span><span class="diff-subject">${escapeHtml(l.subject)}</span>
          <div class="diff-detail">${escapeHtml(l.detail)}</div>
        </div>`)
      .join('');
    $('diff-summary').textContent = `${LAB.diff.summary}   when the task changed, the context changed with it`;
    $('diff-note').textContent = `"${LAB.diff.a}" → "${LAB.diff.b}"`;
  }

  // ---------- compile run ----------
  function reset() {
    running = false;
    $('compile-btn').disabled = false;
    for (const k of Object.keys(stageDone)) delete stageDone[k];
    for (const el of Object.values(stageEls)) el.classList.remove('active', 'done');
    for (const el of Object.values(stageCounts)) el.textContent = '—';
    for (const el of Object.values(counters)) el.textContent = '—';
    $('token-fill').style.width = '0%';
    $('token-label').textContent = `0 / ${preset.budget} (estimated)`;
    $('pipeline-state').textContent = 'idle';
    $('capsule-empty').hidden = false;
    $('capsule-body').hidden = true;
    $('why').hidden = true;
    buildFeed();
    const s = preset.stats;
    animateNumber(counters.sources, s.collected);
    renderDiff();
  }

  function finishStage(stage) {
    stageDone[stage] = true;
    setStage(stage, 'done');
  }

  async function run() {
    if (running) return;
    running = true;
    $('compile-btn').disabled = true;
    reset();
    const rows = new Map([...feedList.children].map((el) => [el.querySelector('.feed-id').textContent, el]));
    const ticks = new Map([...spectrumTicks.children].map((el) => [el.dataset.id, el]));
    const items = preset.items;
    const s = preset.stats;
    const wait = (ms) => new Promise((r) => setTimeout(r, reduced ? 0 : ms));

    // honest stage math from compiler stats
    const bandCount = s.collected - items.filter((i) => i.final === 'rejected' && i.stage === 'RANK').length;
    const rankRejected = items.filter((i) => i.final === 'rejected' && i.stage === 'RANK');
    const verifyRejected = items.filter((i) => i.final === 'rejected' && i.stage === 'VERIFY');
    const resolveOut = items.filter((i) => i.final === 'superseded' || (i.final === 'rejected' && i.stage === 'RESOLVE'));

    // RANK
    $('pipeline-state').textContent = 'running: RANK';
    setStage('RANK', 'active');
    for (const item of rankRejected) {
      const row = rows.get(item.id);
      if (row) row.classList.add('dead');
      const tick = ticks.get(item.id);
      if (tick) tick.classList.add('dead');
      await wait(45);
    }
    for (const item of items) {
      if (item.final === 'rejected' && item.stage === 'RANK') continue;
      const tick = ticks.get(item.id);
      if (tick) tick.classList.add(item.score >= 0.15 ? 'hot' : 'weak');
    }
    animateNumber(counters.band, bandCount);
    stageCounts.RANK.textContent = `${bandCount}/${s.collected}`;
    finishStage('RANK');
    await wait(350);

    // VERIFY
    $('pipeline-state').textContent = 'running: VERIFY';
    setStage('VERIFY', 'active');
    for (const item of verifyRejected) {
      const row = rows.get(item.id);
      if (row) { row.classList.add('dead'); row.querySelector('.feed-state').textContent = '× HEARSAY'; }
      const tick = ticks.get(item.id);
      if (tick) tick.classList.add('dead');
      await wait(80);
    }
    stageCounts.VERIFY.textContent = `${bandCount - verifyRejected.length}`;
    finishStage('VERIFY');
    await wait(350);

    // RESOLVE
    $('pipeline-state').textContent = 'running: RESOLVE';
    setStage('RESOLVE', 'active');
    for (const item of resolveOut) {
      const row = rows.get(item.id);
      if (row) {
        row.classList.add('dead');
        row.querySelector('.feed-state').textContent = item.final === 'superseded' ? '× SUPERSEDED' : '× DUPLICATE';
      }
      const tick = ticks.get(item.id);
      if (tick) tick.classList.add('dead');
      await wait(90);
    }
    animateNumber(counters.conflicts, s.conflicts);
    stageCounts.RESOLVE.textContent = `${s.superseded}×sup ${s.duplicates}×dup`;
    finishStage('RESOLVE');
    await wait(350);

    // COMPRESS
    $('pipeline-state').textContent = 'running: COMPRESS';
    setStage('COMPRESS', 'active');
    for (const item of items) {
      if (item.final === 'selected' || item.final === 'uncertain' || item.final === 'unknown') {
        const row = rows.get(item.id);
        if (row) row.scrollIntoView?.({ block: 'nearest' });
        await wait(28);
      }
    }
    animateNumber(counters.selected, s.selected);
    animateNumber(counters.unknown, preset.capsule.unknown.length);
    animateNumber(counters.tokens, preset.used_tokens);
    stageCounts.COMPRESS.textContent = `${preset.used_tokens}/${preset.budget}`;
    $('token-fill').style.width = `${Math.min(100, (preset.used_tokens / preset.budget) * 100)}%`;
    $('token-label').textContent = `${preset.used_tokens} / ${preset.budget} (estimated)`;
    finishStage('COMPRESS');

    renderCapsule();
    renderRejected();
    $('pipeline-state').textContent = `capsule ready · ${preset.used_tokens} tokens (estimated) · ${s.rejected} rejected on the record`;
    $('compile-btn').disabled = false;
    running = false;
  }

  $('compile-btn').addEventListener('click', run);

  function escapeHtml(text) {
    return String(text).replace(/[&<>"']/g, (ch) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[ch]);
  }

  reset();
})();
